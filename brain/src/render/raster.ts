export type RGB = readonly [number, number, number]

export const WHITE: RGB = [255, 255, 255]
export const BLACK: RGB = [0, 0, 0]

/** 颜色整体调亮调暗：factor 1 不变，小于 1 变暗，大于 1 变亮（到 255 为止）。 */
export function shade(c: RGB, factor: number): RGB {
  return [Math.min(255, Math.round(c[0] * factor)), Math.min(255, Math.round(c[1] * factor)), Math.min(255, Math.round(c[2] * factor))]
}

/** 两个颜色按比例混：t 是 b 占的份量。 */
export function mix(a: RGB, b: RGB, t: number): RGB {
  return [Math.round(a[0] + (b[0] - a[0]) * t), Math.round(a[1] + (b[1] - a[1]) * t), Math.round(a[2] + (b[2] - a[2]) * t)]
}

