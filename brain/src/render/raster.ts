/** 一个字占的宽（含字间距）和一行的高，放大 1 倍时的像素数。 */
export const GLYPH_ADVANCE = 6
export const LINE_HEIGHT = 10

/** 这段字画出来有多宽。 */
export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * GLYPH_ADVANCE - 1) * scale
}

export class Raster {
  readonly width: number
  readonly height: number
  /** 一行接一行、从上到下，每个像素 3 个字节。 */
  readonly data: Uint8Array

  constructor(width: number, height: number, background: RGB = WHITE) {
    this.width = Math.max(1, Math.floor(width))
    this.height = Math.max(1, Math.floor(height))
    this.data = new Uint8Array(this.width * this.height * 3)
    if (background[0] === background[1] && background[1] === background[2]) this.data.fill(background[0])
    else this.fillRect(0, 0, this.width, this.height, background)
  }

  pixel(x: number, y: number): RGB {
    const at = (y * this.width + x) * 3
    return [this.data[at]!, this.data[at + 1]!, this.data[at + 2]!]
  }

  /** 画一行里的一段（左闭右开），画布外的部分不画。alpha 小于 1 时和底下的颜色混。 */
  private span(y: number, x0: number, x1: number, c: RGB, alpha: number): void {
    if (y < 0 || y >= this.height) return
    const from = Math.max(0, x0)
    const to = Math.min(this.width, x1)
    const d = this.data
    let at = (y * this.width + from) * 3
    if (alpha >= 1) {
      for (let x = from; x < to; x++, at += 3) {
        d[at] = c[0]
        d[at + 1] = c[1]
        d[at + 2] = c[2]
      }
      return
    }
    const keep = 1 - alpha
    for (let x = from; x < to; x++, at += 3) {
      d[at] = Math.round(d[at]! * keep + c[0] * alpha)
      d[at + 1] = Math.round(d[at + 1]! * keep + c[1] * alpha)
      d[at + 2] = Math.round(d[at + 2]! * keep + c[2] * alpha)
    }
  }

  fillRect(x: number, y: number, w: number, h: number, c: RGB, alpha = 1): void {
    const x0 = Math.round(x)
    const x1 = Math.round(x + w)
    const y1 = Math.min(this.height, Math.round(y + h))
    for (let row = Math.max(0, Math.round(y)); row < y1; row++) this.span(row, x0, x1, c, alpha)
  }

  /** 矩形的边框，线宽 1 像素，画在矩形里面。 */
  strokeRect(x: number, y: number, w: number, h: number, c: RGB, alpha = 1): void {
    this.fillRect(x, y, w, 1, c, alpha)
    this.fillRect(x, y + h - 1, w, 1, c, alpha)
    this.fillRect(x, y + 1, 1, h - 2, c, alpha)
    this.fillRect(x + w - 1, y + 1, 1, h - 2, c, alpha)
  }

  /**
   * 填一个凸多边形。points 是 x0, y0, x1, y1, ……（像素坐标，可以带小数）。
   * 一个像素算不算在里面看它的中心，边上的归左上：两个共用一条边的多边形既不留缝也不重叠（半透明的面不会在接缝处叠深）。
   */
  fillPolygon(points: readonly number[], c: RGB, alpha = 1): void {
    const n = points.length / 2
    let top = Infinity
    let bottom = -Infinity
    for (let i = 0; i < n; i++) {
      top = Math.min(top, points[i * 2 + 1]!)
      bottom = Math.max(bottom, points[i * 2 + 1]!)
    }
    const yEnd = Math.min(this.height, Math.ceil(bottom - 0.5))
    for (let y = Math.max(0, Math.ceil(top - 0.5)); y < yEnd; y++) {
      const yc = y + 0.5
      let left = Infinity
      let right = -Infinity
      for (let i = 0; i < n; i++) {
        const j = (i + 1) % n
        const ay = points[i * 2 + 1]!
        const by = points[j * 2 + 1]!
        if (!((ay <= yc && yc < by) || (by <= yc && yc < ay))) continue
        const ax = points[i * 2]!
        const x = ax + ((yc - ay) / (by - ay)) * (points[j * 2]! - ax)
        left = Math.min(left, x)
        right = Math.max(right, x)
      }
      if (left < right) this.span(y, Math.ceil(left - 0.5), Math.ceil(right - 0.5), c, alpha)
    }
  }

  /** 一条 1 像素宽的线。 */
  line(x0: number, y0: number, x1: number, y1: number, c: RGB, alpha = 1): void {
    let x = Math.round(x0)
    let y = Math.round(y0)
    const ex = Math.round(x1)
    const ey = Math.round(y1)
    const dx = Math.abs(ex - x)
    const dy = -Math.abs(ey - y)
    const stepX = x < ex ? 1 : -1
    const stepY = y < ey ? 1 : -1
    let err = dx + dy
    for (;;) {
      if (x >= 0 && x < this.width) this.span(y, x, x + 1, c, alpha)
      if (x === ex && y === ey) break
      const e2 = 2 * err
      if (e2 >= dy) {
        err += dy
        x += stepX
      }
      if (e2 <= dx) {
        err += dx
        y += stepY
      }
    }
  }

  /** 写一行字，(x, y) 是左上角。只有 ASCII 可打印字符，别的画成 “?”。 */
  text(x: number, y: number, text: string, c: RGB, scale = 1): void {
    let left = Math.round(x)
    const top = Math.round(y)
    for (const ch of text) {
      const code = ch.codePointAt(0)!
      const glyph = (code >= 32 && code <= 126 ? code : 63) - 32
      for (let column = 0; column < 5; column++) {
        const bits = FONT[glyph * 5 + column]!
        for (let row = 0; row < 8; row++) {
          if ((bits >> row) & 1) this.fillRect(left + column * scale, top + row * scale, scale, scale, c)
        }
      }
      left += GLYPH_ADVANCE * scale
    }
  }

  /** 把另一块画布原样贴上来。 */
  blit(src: Raster, dx: number, dy: number): void {
    for (let y = 0; y < src.height; y++) {
      const ty = y + dy
      if (ty < 0 || ty >= this.height) continue
      const from = Math.max(0, -dx)
      const to = Math.min(src.width, this.width - dx)
      if (from >= to) continue
      this.data.set(src.data.subarray((y * src.width + from) * 3, (y * src.width + to) * 3), (ty * this.width + from + dx) * 3)
    }
  }
}
